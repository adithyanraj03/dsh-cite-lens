// Build lib/client.js: src/client bundled with pdf.js, React left to dsh,
// wrapped in dsh's browser module loader like every other client plugin.
// pdf.js's worker is embedded as a string and started from a blob: URL, so the
// plugin needs no static file route.
//
// esbuild: this package's own devDependency, or (in the dsh workspace) the
// copy installed in the context-governor plugin next door.
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
// Its own esbuild (a devDependency) when installed; otherwise the copy in the
// context-governor plugin next door, as in the dsh workspace this grew up in.
function loadEsbuild() {
  for (const base of [join(here, 'package.json'), join(here, '../context-governor/package.json')]) {
    try {
      return createRequire(base)('esbuild');
    } catch { /* try the next */ }
  }
  throw new Error('esbuild not found: run `npm install` first');
}
const esbuild = loadEsbuild();

const result = await esbuild.build({
  entryPoints: [join(here, 'src/client/index.js')],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  external: ['react'],
  loader: { '.css': 'text' },
  minify: true,
  legalComments: 'none',
  write: false,
  logLevel: 'error',
  supported: { 'top-level-await': false },
});

const worker = readFileSync(join(here, 'node_modules/pdfjs-dist/build/pdf.worker.min.mjs'), 'utf8');
const body = result.outputFiles[0].text;
const wrapped = `// dsh-cite-lens — browser half. GENERATED by build.mjs from src/client; edit those, then npm run build.
// Bundles pdf.js (Apache-2.0, Mozilla Foundation, https://mozilla.github.io/pdf.js/).
window.__ModuleLoader__.load({
  id: "dsh-cite-lens",
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
    var __DSH_CITE_LENS_WORKER__ = ${JSON.stringify(worker)};
${body}
    return module.exports;
  },
});
`;
writeFileSync(join(here, 'lib/client.js'), wrapped);
console.log(`lib/client.js ${(wrapped.length / 1024).toFixed(0)} KB`);
